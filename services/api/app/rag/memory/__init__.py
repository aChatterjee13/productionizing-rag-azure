def optional_setting(settings: Settings, name: str) -> Any:
    """Read a tunable, preferring the real settings field over the local default.

    The rule "every tunable is a settings field with a default, never a literal at a
    call site" still holds: this indirection exists only so a knob this package needs
    can be introduced without editing :mod:`ragcore.settings`, and it disappears the
    moment the field is declared there.

    Args:
        settings: Active settings object.
        name: Field name, e.g. ``"context_compact_every_n_turns"``.

    Returns:
        ``getattr(settings, name)`` when the field exists, otherwise the entry from
        :data:`EXTRA_SETTING_DEFAULTS`.

    Raises:
        KeyError: If ``name`` is neither a settings field nor a declared default,
            which is a programming error rather than a configuration one.
    """
    value = getattr(settings, name, None)
    if value is not None:
        return value
    return EXTRA_SETTING_DEFAULTS[name]


def render_memory_block(
    memories: Sequence[LongTermMemory], *, max_items: int | None = None
) -> str:
    """Render long-term memories for the answer prompt's user turn.

    Memory text is model-authored and PII-redacted before storage, so it is safe to
    place in a prompt. It goes in the *user* turn rather than the system prompt
    because it varies per user and would otherwise destroy the cached prefix.

    Args:
        memories: Memories to render, most relevant first.
        max_items: Optional cap on how many lines are rendered.

    Returns:
        One ``- (kind) text`` line per memory, or an empty string when there is
        nothing to inject.
    """
    selected = list(memories)[:max_items] if max_items else list(memories)
    if not selected:
        return ""
    return "\n".join(f"- ({memory.kind.value}) {memory.text}" for memory in selected)


def render_preferences(profile: UserProfile | None) -> str:
    """Render the rolling user profile as a preferences block.

    Args:
        profile: The user's profile, or None when memory is off or unknown.

    Returns:
        A short block for the user turn, or an empty string when the profile carries
        nothing worth spending tokens on.
    """
    if profile is None or not profile.has_content:
        return ""
    lines: list[str] = []
    if profile.preferred_style:
        lines.append(f"- preferred answer style: {profile.preferred_style}")
    if profile.preferred_language:
        lines.append(f"- preferred language: {profile.preferred_language}")
    if profile.top_topics:
        lines.append(f"- recurring topics: {', '.join(profile.top_topics)}")
    if profile.summary:
        lines.append(f"- profile: {profile.summary}")
    return "\n".join(lines)


def __getattr__(name: str) -> Any:
    """Resolve a lazily re-exported submodule symbol.

    Args:
        name: Attribute being imported from this package.

    Returns:
        The resolved object.

    Raises:
        AttributeError: If the name is not part of the public surface.
    """
    module_path = _LAZY_EXPORTS.get(name)
    if module_path is None:
        msg = f"module {__name__!r} has no attribute {name!r}"
        raise AttributeError(msg)
    value = getattr(importlib.import_module(module_path), name)
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    """List the public surface, including the lazily loaded names.

    Returns:
        Sorted attribute names.
    """
    return sorted(set(__all__) | set(globals()))
