"""Session and durable memory for the RAG pipeline (requirements #2, #3, #5).

Four independent surfaces, all of which the orchestrator composes but none of which
depend on each other at import time:

* :mod:`app.rag.memory.short_term` -- the session window (pipeline stage 2 and 9):
  Redis-backed with an in-memory fallback, rolling-summary maintenance, pinning and
  turn-level token accounting measured with Claude's own tokenizer.
* :mod:`app.rag.memory.long_term` -- durable per-user memories in ``rag_memories``
  (stages 2 and 13): salience-weighted dense recall with decay, structured write-back,
  supersede-based updating, TTL expiry and a hard consent gate.
* :mod:`app.rag.memory.semantic_cache` -- the similar-query retrieval cache
  (stage 4): caches the retrieval *plan*, never the rendered answer, and always
  re-fetches cached chunk ids through the live ACL filter.
* :mod:`app.rag.memory.consolidate` -- the periodic job that merges near-duplicate
  memories, decays salience, expires stale entries and refreshes the user profile.

Submodules are re-exported lazily through :func:`__getattr__` so that importing
``app.rag.memory`` costs nothing: ``long_term`` and ``semantic_cache`` pull
``qdrant-client``, which the short-term path does not need.
"""

